import * as K from '../../src/kernel.js';
import { Document } from '../../src/doc.js';
import { flatPattern } from '../../src/features/sheetmetal.js';
await K.initKernel();
const rect = (w, h, x = 0, y = 0) => ({ pts: { a:{x,y}, b:{x:x+w,y}, c:{x:x+w,y:y+h}, d:{x,y:y+h} }, ents: [ {id:'l1',type:'line',a:'a',b:'b'},{id:'l2',type:'line',a:'b',b:'c'},{id:'l3',type:'line',a:'c',b:'d'},{id:'l4',type:'line',a:'d',b:'a'} ], cons: [] });
const circ = (r, x, y) => ({ pts: { c:{x,y} }, ents: [{id:'c',type:'circle',c:'c',r}], cons: [] });
const vol = (d) => d.state.solid ? K.massProps(d.state.solid).volume.toFixed(1) : 'none';
const errs = (d) => d.features.filter(f => f.error).map(f => f.name + ': ' + f.error);
let d = new Document();
const s1 = d.addFeature('sketch', { plane: { type:'base', name:'Top' }, sketch: rect(100, 60) });
const e1 = d.addFeature('extrude', { sketch: s1.id, op:'add', end:'blind', depth: 20 });
console.log('extrude', vol(d), JSON.stringify(K.bbox(d.state.solid)), errs(d));
const top = d.state.solid.faces.map(f => K.faceSig(f)).find(s => s.n[1] > 0.9);
const s2 = d.addFeature('sketch', { plane: { type:'face', sig: top, plane: { o: top.c, x: [1,0,0], n: [0,1,0] } }, sketch: circ(5, -35, 15) });
const c1 = d.addFeature('extrude', { sketch: s2.id, op:'cut', end:'through' });
console.log('cut', vol(d), 'expected', (120000 - Math.PI*25*20).toFixed(1), errs(d));
const lp = d.addFeature('linearPattern', { features:[c1.id], dir:[1,0,0], spacing: 20, count: 4 });
console.log('pattern', vol(d), 'expected', (120000 - 4*Math.PI*25*20).toFixed(1), errs(d));
const edge = d.state.solid.edges.map(e => K.edgeSig(e)).find(s => Math.abs(s.l-20)<1e-6 && Math.abs(s.m[0])<1e-6 && Math.abs(s.m[2])<1e-6);
d.addFeature('fillet', { edges:[edge], radius: 6 });
console.log('fillet', vol(d), errs(d));
d.addFeature('shell', { faces:[top], thickness: 2 });
console.log('shell', vol(d), errs(d));
d.addFeature('mirror', { features: [], plane: { type:'base', name:'Front' } });
console.log('mirror', vol(d), JSON.stringify(K.bbox(d.state.solid)), errs(d));
// edit upstream: depth 20 -> 30 and check downstream re-resolves
d.updateFeature(e1.id, { ...e1.params, depth: 30 });
console.log('after depth edit', vol(d), JSON.stringify(K.bbox(d.state.solid)), errs(d));
d.undo(); console.log('undo', vol(d)); d.redo(); console.log('redo', vol(d));
const text = d.serialize(); const d2 = Document.deserialize(text); d2.rebuild();
console.log('reload', vol(d2), 'bytes', text.length);
d.setRollback(c1.id); console.log('rollback', vol(d)); d.setRollback(null);
// hole + revolve
d = new Document();
const rs = rect(20, 40, 10, 0); rs.pts.x1 = {x:0,y:0}; rs.pts.x2 = {x:0,y:10}; rs.ents.push({id:'ax',type:'line',a:'x1',b:'x2',construction:true});
const r1 = d.addFeature('sketch', { plane:{type:'base',name:'Front'}, sketch: rs });
d.addFeature('revolve', { sketch: r1.id, angle: 360, op:'add' });
console.log('revolve', vol(d), 'expected', (Math.PI*(900-100)*40).toFixed(1), errs(d));
const hs = { pts:{p:{x:20,y:0}}, ents:[{id:'p',type:'point',p:'p'}], cons:[] };
const h1 = d.addFeature('sketch', { plane:{type:'fixed', plane:{o:[0,40,0],x:[1,0,0],n:[0,1,0]}}, sketch: hs });
const hf = d.addFeature('hole', { sketch: h1.id, diameter: 6, depth: 10, end:'blind', kind:'cbore', cboreDia: 10, cboreDepth: 3 });
console.log('hole', vol(d), errs(d));
d.addFeature('circularPattern', { features:[hf.id], axisO:[0,0,0], axisD:[0,1,0], count: 6, angle: 360 });
console.log('cpattern', vol(d), errs(d));
// sheet metal
d = new Document();
const b1 = d.addFeature('sketch', { plane:{type:'base',name:'Top'}, sketch: rect(100, 60) });
d.addFeature('baseFlange', { sketch: b1.id, thickness: 2, radius: 2, kFactor: 0.44 });
console.log('base flange', vol(d), JSON.stringify(K.bbox(d.state.solid)), errs(d));
const fe = d.state.solid.edges.map(e => K.edgeSig(e)).filter(s => Math.abs(s.l-60)<1e-6 && Math.abs(s.m[0]-100)<1e-6);
console.log('candidate edges', fe.map(s => s.m.join(',')));
const upper = fe.find(s => s.m[1] > 1);
d.addFeature('edgeFlange', { edge: upper, length: 25, angle: 90 });
console.log('edge flange', vol(d), JSON.stringify(K.bbox(d.state.solid)), errs(d), 'valid', K.isValid(d.state.solid));
const fp = flatPattern(d.state.sheetMetal, d.state.flanges);
console.log('flat pattern ents', fp.length, JSON.stringify(fp.slice(-2)));
// weldment
d = new Document();
const w1 = d.addFeature('sketch', { plane:{type:'base',name:'Front'}, sketch: rect(500, 300) });
d.addFeature('structuralMember', { sketch: w1.id, profile:{ type:'Square tube', w:40, t:3 }, miter:true });
console.log('weldment', vol(d), 'expected ~', ((40*40-34*34)*1600).toFixed(0), JSON.stringify(K.bbox(d.state.solid)), errs(d), d.state.cutlist.length);
// surface + thicken, loft, sweep
d = new Document();
const o1 = { pts:{a:{x:0,y:0},b:{x:50,y:0},c:{x:50,y:30}}, ents:[{id:'l1',type:'line',a:'a',b:'b'},{id:'l2',type:'line',a:'b',b:'c'}], cons:[] };
const q1 = d.addFeature('sketch', { plane:{type:'base',name:'Front'}, sketch: o1 });
const sf = d.addFeature('surfExtrude', { sketch: q1.id, depth: 40, end:'blind' });
console.log('surface bodies', d.state.surfaces.length, errs(d));
d.addFeature('thicken', { surface: sf.id, thickness: 2 });
console.log('thicken', vol(d), d.state.surfaces.length, errs(d));
const pc = d.addFeature('sketch', { plane:{type:'base',name:'Top'}, sketch: circ(4, 0, 0) });
d.addFeature('sweep', { profile: pc.id, path: q1.id, op:'add' });
console.log('sweep', vol(d), errs(d));
const t1 = d.addFeature('sketch3d', { pts:[[0,0,0],[0,100,0],[80,100,0],[80,100,60]], lines:[[0,1],[1,2],[2,3]] });
d.addFeature('structuralMember', { sketch: t1.id, profile:{ type:'Pipe', w:20, t:2 }, miter:true });
console.log('3d weldment', vol(d), errs(d));
